-- Run in the Supabase SQL Editor. This table only stores email and signup time.
create table if not exists public.early_access (
  id bigint generated by default as identity primary key,
  email text not null unique check (char_length(email) <= 254),
  created_at timestamptz not null default now()
);

alter table public.early_access enable row level security;
grant insert on public.early_access to anon;
grant usage, select on sequence public.early_access_id_seq to anon;
create policy "Allow public early-access signups"
  on public.early_access for insert to anon
  with check (email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$');
